source("R/spatial.R")
root <- tempfile(); dir.create(root)
# Cells have independently specified known areas; polygons must preserve holes.
d <- data.frame(x=c(0.25,0.75,1.25,1.75), y=rep(0.5,4),code=c(10L,30L,95L,50L),slope=c(1L,3L,0L,3L),area_ha=c(1,2,3,4))
saveRDS(d,file.path(root,"block.rds"))
p <- list(root=root,index=list(blocks=data.frame(file="block.rds",xmin=0,xmax=2,ymin=0,ymax=1)))
geom <- polygon_geometry('[[[0,0],[2,0],[2,1],[0,1],[0,0]]]')
a <- polygon_areas(p,geom)
stopifnot(sum(a$area_ha)==10,a$area_ha[a$code==95]==3)
hole <- polygon_geometry('[[[0,0],[2,0],[2,1],[0,1],[0,0]],[[0.1,0.1],[0.4,0.1],[0.4,0.9],[0.1,0.9],[0.1,0.1]]]')
stopifnot(sum(polygon_areas(p,hole)$area_ha)==9)
stopifnot(inherits(try(polygon_geometry('[[[0,0],[1,1],[0,1],[1,0],[0,0]]]'),silent=TRUE),"try-error"))
cl <- classify_areas(a,DEFAULTS)
stopifnot(abs(sum(cl$pct)-100)<1e-10, !95 %in% cl$code)
changed <- DEFAULTS; changed['30'] <- 3
stopifnot(classify_areas(a,changed)$score[classify_areas(a,changed)$code==30]==3)
r <- render_grid(p,c(0,2,0,1),max_dimension=4)
stopifnot(terra::ncell(r)<=16,sum(terra::values(r[['mangrove']])==1,na.rm=TRUE)==1)
stopifnot(identical(as.integer(na.omit(terra::values(r[['landcover']]))),as.integer(d$code)))
empty <- polygon_geometry('[[[10,10],[11,10],[11,11],[10,11],[10,10]]]')
stopifnot(sum(polygon_areas(p,empty)$area_ha)==0)
# Correct order of magnitude: source-resolution cells are approximately 1 ha.
cell <- terra::rast(nrows=1,ncols=1,xmin=0,xmax=0.000898315284119522,ymin=0,ymax=0.000898315284119522,crs="EPSG:4326")
stopifnot(abs(terra::values(terra::cellSize(cell,unit="ha"))-1)<0.02)
unlink(root,recursive=TRUE)
cat("PASS: polygon geometry/holes/invalid input, area totals, class percentages, reclassification, bounded display, empty selection, source cell area.\n")
